def check_operator(name_list):
    """The excess over the threshold needs ordered values."""
    if name_list['operator'] in ('==', '!='):
        raise ValueError("forecast_mode 'flow' needs an ordered operator ('>', '>=', '<', '<='), not "
                         f"{name_list['operator']!r}.")


def read_frame(path, name_list, aux=()):
    """One frame of the tracking table (the columns of the model), the identity of a cluster in uid and its
    vectors in pixels."""
    names = pq.read_schema(path).names
    df = pd.read_parquet(path, columns=[c for c in COLUMNS + list(aux) if c in names])
    if 'iuid' in df.columns:
        df['uid'] = df['iuid'].where(df['iuid'].notna(), df['uid'])
    return to_pixels(df, name_list)


def base_image(window_df, history_df, name_list, lead=0):
    """
    The base the network corrects: the persistence forecast of the next frame with
    the trends of morph_trend (persistence.persistence with morph_trend on), the
    trends taken from history_df and damped with the lead time.
    """
    moved = moved_clusters(window_df, name_list)
    if not moved.empty:
        moved = apply_trends(moved, history_df, name_list, lead)
    return render(moved, name_list)


def encode(image, name_list, scale):
    """The field of an image: excess over the first threshold (signed) divided by scale, OUTSIDE where NaN."""
    sign = operator_sign(name_list['operator'])
    excess = sign * (image - float(name_list['thresholds'][0])) / scale
    return np.where(np.isfinite(image), np.maximum(excess, 0.0), OUTSIDE).astype(np.float32)


def decode(field, name_list, scale):
    """The image of a field: the values of the pixels inside a system (field above OUTSIDE / 2), NaN elsewhere."""
    sign = operator_sign(name_list['operator'])
    # A pixel inside a system is at least on the first threshold (strictly beyond it for '>' and '<')
    excess = np.maximum(field, 1e-3) * scale
    return np.where(field > OUTSIDE / 2, float(name_list['thresholds'][0]) + sign * excess, np.nan)


def frame_image(frame, name_list):
    """The image of the pixels of the clusters of a frame (NaN elsewhere)."""
    h, w = name_list['y_dim'], name_list['x_dim']
    image = np.full(h * w, np.nan)
    if not frame.empty:
        xs = np.concatenate(frame['array_x'].to_numpy()).astype(np.int64)
        ys = np.concatenate(frame['array_y'].to_numpy()).astype(np.int64)
        image[ys * w + xs] = np.concatenate(frame['array_values'].to_numpy()).astype(float)
    return image.reshape(h, w)


def labels(frame, rows, name_list):
    """Index of the step of each pixel (rows: the step of each cluster of the frame, -1 none), the innermost
    threshold over the outer ones; -1 outside the clusters."""
    h, w = name_list['y_dim'], name_list['x_dim']
    label = np.full(h * w, -1, dtype=np.int32)
    if not frame.empty:
        order = np.argsort(frame['threshold_level'].to_numpy(), kind='stable')
        n_pix = frame['array_x'].map(len).to_numpy()[order]
        xs = np.concatenate(frame['array_x'].to_numpy()[order]).astype(np.int64)
        ys = np.concatenate(frame['array_y'].to_numpy()[order]).astype(np.int64)
        label[ys * w + xs] = np.repeat(np.asarray(rows)[order], n_pix)
    return label.reshape(h, w)


def optical_flow(frame, name_list):
    """
    The optical flow vectors of a frame (column opt_field: lines from the previous to
    the current position of each tracked point, in degrees, or pixels without lat/lon)
    spread over the grid with a gaussian of OPT_SIGMA pixels, in pixels per step;
    NaN where there are none (opt_correction off).
    """
    h, w = name_list['y_dim'], name_list['x_dim']
    flow = np.full((2, h, w), np.nan, dtype=np.float32)
    if frame.empty or 'opt_field' not in frame.columns:
        return flow
    wkts = [s for s in frame['opt_field'].dropna().unique() if s and 'EMPTY' not in s]
    if not wkts:
        return flow
    lines = shapely.get_parts(shapely.from_wkt(wkts))
    coords, index = shapely.get_coordinates(lines, return_index=True)
    if not len(coords):
        return flow
    if all(name_list.get(k) is not None for k in ['lat_min', 'lat_max', 'lon_min', 'lon_max']):
        coords = np.column_stack([(coords[:, 0] - name_list['lon_min']) / name_list['x_res'],
                                  (coords[:, 1] - name_list['lat_min']) / name_list['y_res']])
    first = np.unique(index, return_index=True)[1]
    last = np.r_[first[1:], len(index)] - 1
    steps = np.maximum(last - first, 1)
    u = (coords[last, 0] - coords[first, 0]) / steps
    v = (coords[last, 1] - coords[first, 1]) / steps
    x = np.clip(np.floor(coords[last, 0]).astype(np.int64), 0, w - 1)
    y = np.clip(np.floor(coords[last, 1]).astype(np.int64), 0, h - 1)
    sums = np.zeros((3, h, w))
    np.add.at(sums[0], (y, x), u)
    np.add.at(sums[1], (y, x), v)
    np.add.at(sums[2], (y, x), 1.0)
    sums = np.stack([ndimage.gaussian_filter(s, OPT_SIGMA) for s in sums])
    has = sums[2] > 1e-3
    flow[0][has] = sums[0][has] / sums[2][has]
    flow[1][has] = sums[1][has] / sums[2][has]
    return flow


def map_table(df, name_list, aux, window):
    """The steps of the clusters (rnn_model.step_table) with the columns of MAPS and aux."""
    table = step_table(df, name_list, aux, window)
    table['lifetime_log'] = np.log1p(table['lifetime_steps'].clip(lower=0))
    return table


def step_rows(frame, table):
    """The row of table (the step) of each cluster of frame, -1 when it has none."""
    keys = ['timestamp', 'threshold_level', 'uid']
    pos = table[keys].reset_index(drop=True).reset_index().rename(columns={'index': 'row'})
    rows = frame[keys].reset_index(drop=True).merge(pos, on=keys, how='left')['row']
    return rows.fillna(-1).astype(np.int64).to_numpy()


def normalized_maps(table, columns, mean, std):
    """The maps of the steps z-scored with the statistics of the training (NaN to 0), plus a last row of zeros
    (pixels outside the clusters, label -1)."""
    x = (table[columns].to_numpy(dtype=float) - np.asarray(mean)) / np.asarray(std)
    x = np.nan_to_num(x, nan=0.0, posinf=0.0, neginf=0.0)
    return np.vstack([x, np.zeros((1, len(columns)))]).astype(np.float32)


def conditions(base, context, label, flow, maps, columns, mean, std):
    """
    Inputs of the network (CHANNELS) on a grid or a crop: base and context fields,
    the maps of the steps of the clusters (rows of maps by label) and the optical
    flow (normalized as the mean vector, which fills the pixels without flow).
    """
    m = maps[label].transpose(2, 0, 1)
    inside = label >= 0
    iu, iv = columns.index('window_u_mean'), columns.index('window_v_mean')
    opt = []
    for comp, i in ((flow[0], iu), (flow[1], iv)):
        z = (comp - mean[i]) / std[i]
        opt.append(np.where(inside, np.where(np.isfinite(z), z, m[i]), 0.0))
    return np.concatenate([base[None], np.stack(context), m, np.stack(opt)]).astype(np.float32)


def probability_matched_mean(members):
    """The mean of the members (M, H, W) with the distribution of all their values (probability matching)."""
    m = len(members)
    mean = members.mean(0)
    pooled = np.sort(members.ravel())[m // 2::m][:mean.size]
    out = np.empty(mean.size, dtype=members.dtype)
    out[np.argsort(mean.ravel(), kind='stable')] = pooled
    return out.reshape(mean.shape)


def frames_of(files, name_list, aux):
    """The frames of files, with their timestamps."""
    frames = [read_frame(f, name_list, aux) for f in files]
    return frames, [frame_time(f) for f in files]


def build_dataset(name_list, files, aux, window):
    """
    Fields, labels, optical flow and bases of the frames of files, the steps of
    their clusters and the training samples: the frames whose next frame is one
    delta_time later (the target), with the indexes of their context frames.
    """
    dt = pd.to_timedelta(name_list['delta_time'], unit='m')
    frames, times = frames_of(files, name_list, aux)
    table = map_table(pd.concat(frames, ignore_index=True), name_list, aux, window)
    sign = operator_sign(name_list['operator'])
    values = np.concatenate([np.concatenate(f['array_values'].to_numpy()) for f in frames if not f.empty] or
                            [np.zeros(1)]).astype(float)
    excess = sign * (values - float(name_list['thresholds'][0]))
    scale = float(np.std(excess[excess >= 0])) if (excess >= 0).any() else 1.0
    scale = scale if scale > 1e-6 else 1.0
    n, h, w = len(frames), name_list['y_dim'], name_list['x_dim']
    data = dict(field=np.empty((n, h, w), np.float16), label=np.empty((n, h, w), np.int32),
                flow=np.empty((n, 2, h, w), np.float16), base=np.full((n, h, w), OUTSIDE, np.float16))
    print(f"  * FLOW: preparing {n} frames (fields, history maps, optical flow and persistence bases)")
    for i, frame in enumerate(frames):
        data['field'][i] = encode(frame_image(frame, name_list), name_list, scale)
        data['label'][i] = labels(frame, step_rows(frame, table), name_list)
        data['flow'][i] = optical_flow(frame, name_list)
    samples = []
    for i in range(n - 1):
        if times[i + 1] - times[i] != dt or frames[i].empty:
            continue
        # The window of the persistence: the frames of the last `window` time steps
        win = [k for k in range(max(i - window + 1, 0), i + 1) if times[i] - times[k] < dt * window]
        window_df = pd.concat([frames[k] for k in win], ignore_index=True)
        data['base'][i] = encode(base_image(window_df, window_df, name_list), name_list, scale)
        context = [i - k if i - k >= 0 and times[i] - times[i - k] == dt * k else -1 for k in range(CONTEXT)]
        samples.append((i, context))
        if len(samples) % 200 == 0:
            print(f"    {len(samples)} samples")
    return data, table, scale, samples


def sample_inputs(data, maps, columns, mean, std, chain, y0, x0, size, generated=()):
    """
    Inputs, target (residual of the next field over the base), weight and base of a
    sample on a crop: the sample chain[len(generated)] of a chain of consecutive
    samples, the frames of the previous ones being the fields generated by the model
    (generated[m]: the field of the frame after chain[m]), as in the forecast, where
    the next lead time reads the forecast frames. Their base is the observed one with
    the error of the generated frame it starts from (the persistence moves that
    frame), an approximation that avoids tracking the generated frames.
    """
    j = len(generated)
    i, context = chain[j]
    sl = (slice(y0, y0 + size), slice(x0, x0 + size))
    base = data['base'][i][sl].astype(np.float32)
    if j:
        base = np.maximum(base + generated[-1] - data['field'][i][sl], OUTSIDE)
    ctx = [generated[j - 1 - k] if k < j else
           data['field'][f][sl].astype(np.float32) if f >= 0 else np.full((size, size), OUTSIDE, np.float32)
           for k, f in enumerate(context)]
    cond = conditions(base, ctx, data['label'][i][sl], data['flow'][i][(slice(None),) + sl].astype(np.float32),
                      maps, columns, mean, std)
    target = data['field'][i + 1][sl].astype(np.float32) - base
    near = (data['field'][i + 1][sl] > OUTSIDE / 2) | (base > OUTSIDE / 2) | (ctx[0] > OUTSIDE / 2)
    weight = np.where(ndimage.binary_dilation(near, iterations=4), 1.0, BACKGROUND).astype(np.float32)
    return cond, target, weight, base


def chains(samples, length):
    """The chains of `length` consecutive samples (the frame after each one starts the next one)."""
    by_frame = {item[0]: item for item in samples}
    return [[by_frame[i + m] for m in range(length)] for i in by_frame
            if all(i + m in by_frame for m in range(length))]


def crop_origin(data, chain, size, rng):
    """Corner of a crop of side size centered on a random pixel of the systems of the first sample of chain."""
    i, _ = chain[0]
    h, w = data['field'].shape[1:]
    inside = np.flatnonzero((data['field'][i + 1] > OUTSIDE / 2) | (data['base'][i] > OUTSIDE / 2))
    p = rng.choice(inside) if len(inside) else rng.integers(h * w)
    cy, cx = divmod(int(p), w)
    return int(np.clip(cy - size // 2, 0, h - size)), int(np.clip(cx - size // 2, 0, w - size))


def flow_loss(model, cond, target, weight):
    """Flow matching loss with x-prediction: the network predicts the residual from its noisy state, at flow
    times tau drawn from a logit-normal distribution."""
    noise = torch.randn_like(target)
    tau = torch.sigmoid(torch.randn(len(cond), device=target.device))
    t = tau[:, None, None, None]
    state = (1 - t) * noise + t * target
    pred = model(state, cond, tau)
    return ((pred - target) ** 2 * weight).sum() / weight.sum().clamp(min=1)


def split(samples):
    """Train/validation split: the last VAL_FRAC of the frames."""
    cut = int(np.floor(len(samples) * (1 - VAL_FRAC)))
    return samples[:cut], samples[cut:]


def model_name(name_list, files, aux, window):
    """
    File name of a trained model, e.g.
    flow_202511010000-202511072350_le235-210_dt10min_win6_ctx3_b32_1a2b3c4d.pt:
    mode, training period (first and last frames), operator and thresholds of the
    tracking, delta_time, observation_window (frames of the persistence base),
    context frames, base channels of the network, the auxiliary columns (aux-...)
    and a hash of all the settings.
    """
    arch = dict(DEFAULT_ARCH, **(name_list.get('rnn_arch') or {}))
    thresholds = '-'.join(f'{float(t):g}' for t in name_list['thresholds'])
    parts = ['flow', f"{frame_time(files[0]):%Y%m%d%H%M}-{frame_time(files[-1]):%Y%m%d%H%M}",
             f"{OPERATOR_NAMES.get(name_list['operator'], 'op')}{thresholds}",
             f"dt{float(name_list['delta_time']):g}min", f"win{window}", f"ctx{CONTEXT}", f"b{arch['base']}"]
    if aux:
        parts.append('aux-' + '-'.join(re.sub(r'[^A-Za-z0-9.]+', '', c) for c in aux))
    return '_'.join(parts) + f"_{settings_key(name_list, files, aux, window)}.pt"


def settings_key(name_list, files, aux, window):
    """Hash of everything that changes the trained model, which names its checkpoint."""
    settings = dict(mode='flow', arch=name_list.get('rnn_arch'), aux=aux, window=window,
                    thresholds=list(map(float, name_list['thresholds'])), operator=name_list['operator'],
                    delta_time=name_list['delta_time'], x_res=name_list.get('x_res'),
                    y_res=name_list.get('y_res'), x_dim=name_list.get('x_dim'), y_dim=name_list.get('y_dim'),
                    files=[pathlib.Path(files[0]).name, pathlib.Path(files[-1]).name, len(files),
                           os.path.getmtime(files[-1])],
                    training=[EPOCHS, PATIENCE, BATCH, CROP, CROPS, SEED, VAL_FRAC, EMA, BACKGROUND, ROLLOUT,
                              ROLLOUT_PROB, CONTEXT, OUTSIDE, OPT_SIGMA, FORMAT])
    return hashlib.sha1(json.dumps(settings, sort_keys=True, default=str).encode()).hexdigest()[:8]


def train(torch, name_list):
    """
    Train the model on the frames of training_files (the whole tracking up to
    forecast_time, or name_list['rnn_train_period']), or reuse the checkpoint of a
    previous run with the same settings, saved in output_path/forecast/models/
    (see model_name). Returns the checkpoint.
    """
    check_operator(name_list)
    files = training_files(name_list)
    aux = list(name_list.get('rnn_aux') or [])
    validate_aux(files, aux)
    window = int(name_list.get('observation_window') or 3)
    train_start, train_until = frame_time(files[0]), frame_time(files[-1])
    path = pathlib.Path(name_list['output_path']) / 'forecast' / 'models' / model_name(name_list, files, aux, window)
    if path.exists():
        print(f"  * FLOW: reusing the model trained with the same settings: {path}")
        return dict(load_checkpoint(torch, path, name_list), path=str(path))

    arch = dict(DEFAULT_ARCH, **(name_list.get('rnn_arch') or {}))
    device = pick_device(torch, arch['device'])
    data, table, scale, samples = build_dataset(name_list, files, aux, window)
    columns = list(MAPS) + aux
    mean = table[columns].mean().fillna(0).to_numpy(dtype=float)
    std = table[columns].std().fillna(1).replace(0, 1).to_numpy(dtype=float)
    maps = normalized_maps(table, columns, mean, std)
    seed_everything(torch)
    model = FlowUNet(len(CHANNELS) - 1 + len(aux), base=int(arch['base']))
    ckpt = dict(format=FORMAT, mode='flow', pyfortracc_version=__version__.strip().strip('"'),
                torch_version=str(torch.__version__), maps=columns, aux=aux, window=window, context=CONTEXT,
                operator=name_list['operator'], thresholds=list(map(float, name_list['thresholds'])),
                delta_time=float(name_list['delta_time']), x_res=float(name_list['x_res']),
                y_res=float(name_list['y_res']), train_start=str(train_start), train_until=str(train_until),
                n_frames=len(files), map_mean=mean.tolist(), map_std=std.tolist(), scale=scale)

    if len(samples) < MIN_SAMPLES:
        print(f"  * FLOW: only {len(samples)} training frames up to {train_until}; the model is not trained "
              f"and forecasts the persistence with the trends of the window.")
        ckpt.update(arch=arch, n_train=len(samples), n_val=0, val_loss=None, baseline_loss=None)
    else:
        tr, va = split(samples)
        size = min(CROP, data['field'].shape[1], data['field'].shape[2]) // 8 * 8
        rng = np.random.default_rng(SEED)
        train_chains = {chain[0][0]: chain for chain in chains(tr, ROLLOUT)}
        # Fixed crops and noises of the validation, on rollouts as long as the ones of the training
        val_chains = [(chain, crop_origin(data, chain, size, rng)) for chain in
                      (chains(va, ROLLOUT) or [[item] for item in va])]
        print(f"  * FLOW: training on {len(tr)} frames (validation {len(va)}) from {train_start} to "
              f"{train_until}, crops of {size} px, rollouts of {ROLLOUT} frames, device {device}")

        def tensors(group, generated):
            out = [sample_inputs(data, maps, columns, mean, std, chain, y0, x0, size, g)
                   for (chain, (y0, x0)), g in zip(group, generated)]
            cond, target, weight, base = [torch.as_tensor(np.stack(a)).to(device) for a in zip(*out)]
            return cond, target[:, None], weight[:, None], base[:, None]

        def advance(net, generated, cond, base, gen=None):
            # Generate the residual of a step (zero without net, the persistence with the trends) and
            # append the generated fields, read by the next step
            noise = torch.randn(base.shape, generator=gen).to(device) if gen is not None else torch.randn_like(base)
            with torch.no_grad():
                pred = euler(net, cond, noise) if net is not None else torch.zeros_like(base)
            for g, field in zip(generated, (base + pred)[:, 0].cpu().numpy()):
                g.append(field)
            return pred

        def validate(net):
            # Error of the generated residuals (from noise, STEPS steps) along the rollouts: the
            # forecast itself, the frames after the first one reading the generated ones
            gen = torch.Generator().manual_seed(SEED)
            total, wsum = 0.0, 0.0
            if net is not None:
                net.eval()
            for k in range(0, len(val_chains), BATCH):
                group = val_chains[k:k + BATCH]
                generated = [[] for _ in group]
                for _ in range(len(group[0][0])):
                    cond, target, weight, base = tensors(group, generated)
                    pred = advance(net, generated, cond, base, gen)
                    total += float(((pred - target) ** 2 * weight).sum())
                    wsum += float(weight.sum())
            return total / max(wsum, 1)

        model = model.to(device)
        ema = copy.deepcopy(model).eval()
        optim = torch.optim.AdamW(model.parameters(), lr=float(arch['lr']), weight_decay=float(arch['weight_decay']))
        best, best_state, wait = np.inf, None, 0
        baseline = validate(None)
        for epoch in range(EPOCHS):
            # Single steps and rollouts (pushforward): the model generates the first frames of the
            # rollout without gradient and learns the last one from them
            groups = {1: [], ROLLOUT: []}
            for item in tr:
                for _ in range(CROPS):
                    chain = (train_chains.get(item[0]) if rng.random() < ROLLOUT_PROB else None) or [item]
                    groups[len(chain)].append((chain, crop_origin(data, chain, size, rng)))
            batches = [[g[j] for j in order[k:k + BATCH]] for g in groups.values()
                       for order in [rng.permutation(len(g))] for k in range(0, len(g), BATCH)]
            model.train()
            for b in rng.permutation(len(batches)):
                group = batches[b]
                generated = [[] for _ in group]
                for _ in range(len(group[0][0]) - 1):
                    cond, _, _, base = tensors(group, generated)
                    advance(model, generated, cond, base)
                cond, target, weight, _ = tensors(group, generated)
                optim.zero_grad()
                loss = flow_loss(model, cond, target, weight)
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                optim.step()
                with torch.no_grad():
                    for pe, pm in zip(ema.parameters(), model.parameters()):
                        pe.lerp_(pm, 1 - EMA)
            val = validate(ema)
            print(f"    epoch {epoch + 1}: validation loss {val:.4f} (persistence + trends: {baseline:.4f})")
            if val < best - 1e-6:
                best, wait = val, 0
                best_state = {k: v.detach().cpu().clone() for k, v in ema.state_dict().items()}
            else:
                wait += 1
                if wait >= PATIENCE:
                    break
        model.load_state_dict(best_state)
        print(f"  * FLOW: validation loss {best:.4f} (persistence + trends: {baseline:.4f})")
        ckpt.update(arch=arch, n_train=len(tr), n_val=len(va), val_loss=best, baseline_loss=baseline)
    # Plain python values, which torch.load(weights_only=True) accepts
    ckpt['arch'] = {k: (str(v) if k == 'device' else int(v) if k == 'base' else float(v))
                    for k, v in ckpt['arch'].items()}
    ckpt['state_dict'] = {k: v.detach().cpu() for k, v in model.state_dict().items()}
    ckpt['path'] = str(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(ckpt, path)
    print(f"  * FLOW: weights saved in {path} (name_list['rnn_weights'] to reuse them)")
    return ckpt


def load_checkpoint(torch, path, name_list):
    """A checkpoint written by train(), checked against the name_list."""
    if not pathlib.Path(path).exists():
        raise FileNotFoundError(f"name_list['rnn_weights']: {path} not found.")
    ckpt = torch.load(path, map_location='cpu', weights_only=True)
    if ckpt.get('format') != FORMAT or ckpt.get('mode') != 'flow':
        raise ValueError(f"{path} is not a pyfortracc 'flow' model (mode {ckpt.get('mode')!r}).")
    for key, value in (('operator', name_list['operator']),
                       ('thresholds', list(map(float, name_list['thresholds']))),
                       ('delta_time', float(name_list['delta_time']))):
        if ckpt[key] != value:
            raise ValueError(f"The model {path} was trained with {key} = {ckpt[key]}, "
                             f"but the name_list has {value}.")
    if not np.isclose(ckpt['x_res'], name_list['x_res']) or not np.isclose(ckpt['y_res'], name_list['y_res']):
        print(f"  * Warning: the model {path} was trained on a grid of another resolution; its fields "
              f"and vectors are in pixels per time step.")
    aux = list(name_list.get('rnn_aux') or [])
    if aux and aux != ckpt['aux']:
        print(f"  * Warning: name_list['rnn_aux'] = {aux}, but the model uses {ckpt['aux']}.")
    return ckpt


def generate(model, cond, device, seed=SEED):
    """
    MEMBERS residuals for the inputs cond (C, H, W): from noise to the residual in
    STEPS Euler steps of the flow, the network predicting the residual (x-prediction).
    Returns (MEMBERS, H, W).
    """
    h, w = cond.shape[1:]
    ph, pw = -h % 8, -w % 8
    cond = np.pad(cond, ((0, 0), (0, ph), (0, pw)), mode='edge')
    gen = torch.Generator().manual_seed(seed)
    c = torch.as_tensor(cond, device=device)[None].expand(MEMBERS, -1, -1, -1)
    with torch.no_grad():
        state = euler(model, c, torch.randn((MEMBERS, 1) + cond.shape[1:], generator=gen).to(device))
    return state[:, 0, :h, :w].cpu().numpy()


def euler(model, cond, state):
    """The residuals generated from the noises state in STEPS Euler steps of the flow, the network predicting
    the residual (x-prediction): the velocity is (prediction - state) / (1 - tau)."""
    for k in range(STEPS):
        tau, nxt = k / STEPS, (k + 1) / STEPS
        pred = model(state, cond, torch.full((len(state),), tau, device=state.device))
        state = state + (nxt - tau) * (pred - state) / (1 - tau)
    return state


def build_forecaster(name_list):
    """
    The forecast function of the flow model, with the forecast.persistence
    signature: forecast_function(tracked_files, name_list, lead, history_files).

    The model is loaded from name_list['rnn_weights'] or trained (see train) once,
    before the lead times. At every lead time its inputs are the frames of
    tracked_files (the observation window, then the forecast frames re-extracted and
    re-linked by the tracking at the previous lead times).
    """
    check_operator(name_list)
    torch = import_torch()
    if name_list.get('rnn_weights'):
        ckpt = load_checkpoint(torch, name_list['rnn_weights'], name_list)
        observed_files = training_files(dict(name_list, rnn_train_period=None))
        validate_aux(observed_files, ckpt['aux'])
        print(f"  * FLOW: weights loaded from {name_list['rnn_weights']} (trained on "
              f"{ckpt['train_start']} to {ckpt['train_until']})")
    else:
        ckpt = train(torch, name_list)
    arch, aux, window, scale = ckpt['arch'], ckpt['aux'], ckpt['window'], ckpt['scale']
    columns, mean, std = ckpt['maps'], np.asarray(ckpt['map_mean']), np.asarray(ckpt['map_std'])
    device = pick_device(torch, arch.get('device', 'auto'))
    model = FlowUNet(len(CHANNELS) - 1 + len(aux), base=int(arch['base']))
    model.load_state_dict(ckpt['state_dict'])
    model = model.to(device).eval()
    dt = pd.to_timedelta(name_list['delta_time'], unit='m')

    def forecast_function(tracked_files, name_list, lead=0, history_files=None):
        frames, times = frames_of(tracked_files, name_list, aux)
        window_df = pd.concat(frames, ignore_index=True)
        history_df = window_df if history_files is None else \
            pd.concat(frames_of(history_files, name_list, aux)[0], ignore_index=True)
        base = base_image(window_df, history_df, name_list, lead)
        if frames[-1].empty:
            return base
        table = map_table(window_df, name_list, aux, window)
        maps = normalized_maps(table, columns, mean, std)
        current = frames[-1]
        label = labels(current, step_rows(current, table), name_list)
        context = []
        for k in range(CONTEXT):
            i = len(frames) - 1 - k
            ok = i >= 0 and times[-1] - times[i] == dt * k
            context.append(encode(frame_image(frames[i], name_list), name_list, scale) if ok else
                           np.full(label.shape, OUTSIDE, np.float32))
        base_field = encode(base, name_list, scale)
        cond = conditions(base_field, context, label, optical_flow(current, name_list), maps, columns, mean, std)
        residual = probability_matched_mean(generate(model, cond, device))
        return decode(base_field + residual, name_list, scale)

    return forecast_function



class Block(nn.Module):
    """Residual block of two convolutions, modulated by the flow time (scale and shift)."""

    def __init__(self, c_in, c_out, emb):
        super().__init__()
        self.norm1 = nn.GroupNorm(8, c_in)
        self.conv1 = nn.Conv2d(c_in, c_out, 3, padding=1)
        self.film = nn.Linear(emb, 2 * c_out)
        self.norm2 = nn.GroupNorm(8, c_out)
        self.conv2 = nn.Conv2d(c_out, c_out, 3, padding=1)
        self.skip = nn.Conv2d(c_in, c_out, 1) if c_in != c_out else nn.Identity()

    def forward(self, x, e):
        h = self.conv1(F.silu(self.norm1(x)))
        scale, shift = self.film(e)[:, :, None, None].chunk(2, dim=1)
        h = self.conv2(F.silu(self.norm2(h) * (1 + scale) + shift))
        return h + self.skip(x)


class Attention(nn.Module):
    """Self-attention over the pixels of the coarsest level (the interactions between distant systems)."""

    def __init__(self, c, heads=4):
        super().__init__()
        self.heads = heads
        self.norm = nn.GroupNorm(8, c)
        self.qkv = nn.Conv2d(c, 3 * c, 1)
        self.proj = nn.Conv2d(c, c, 1)

    def forward(self, x):
        b, c, h, w = x.shape
        q, k, v = self.qkv(self.norm(x)).reshape(b, 3, self.heads, c // self.heads, h * w).transpose(-1, -2) \
            .unbind(1)
        out = F.scaled_dot_product_attention(q, k, v)
        return x + self.proj(out.transpose(-1, -2).reshape(b, c, h, w))


class FlowUNet(nn.Module):
    """
    U-Net of the residual flow: four levels (base, 2 base, 4 base, 4 base channels,
    the grid divided by 1, 2, 4 and 8), self-attention at the coarsest one, every
    block modulated by the flow time. It reads the state of the flow and the inputs
    (CHANNELS) and predicts the residual (x-prediction).

    Parameters
    ----------
    n_cond : int
        Input channels besides the state of the flow (CHANNELS with the auxiliary
        columns).
    base : int
        Channels of the first level (name_list['rnn_arch']).
    """

    def __init__(self, n_cond, base=32):
        super().__init__()
        ch = [base, 2 * base, 4 * base, 4 * base]
        emb = 4 * base
        self.base = base
        self.time = nn.Sequential(nn.Linear(base, emb), nn.SiLU(), nn.Linear(emb, emb))
        self.inp = nn.Conv2d(1 + n_cond, ch[0], 3, padding=1)
        self.enc = nn.ModuleList([Block(ch[max(i - 1, 0)], ch[i], emb) for i in range(4)])
        self.down = nn.ModuleList([nn.Conv2d(ch[i], ch[i], 3, stride=2, padding=1) for i in range(3)])
        self.mid1, self.attn, self.mid2 = Block(ch[3], ch[3], emb), Attention(ch[3]), Block(ch[3], ch[3], emb)
        self.dec = nn.ModuleList([Block(2 * ch[i], ch[i], emb) for i in range(4)])
        self.up = nn.ModuleList([nn.Conv2d(ch[i + 1], ch[i], 3, padding=1) for i in range(3)])
        self.out = nn.Sequential(nn.GroupNorm(8, ch[0]), nn.SiLU(), nn.Conv2d(ch[0], 1, 3, padding=1))
        # Zero output at the start: the persistence with the trends of the window
        nn.init.zeros_(self.out[-1].weight)
        nn.init.zeros_(self.out[-1].bias)

    def embedding(self, tau):
        half = self.base // 2
        freq = torch.exp(-math.log(10000.0) * torch.arange(half, device=tau.device) / half)
        angle = 1000.0 * tau[:, None] * freq[None]
        return self.time(torch.cat([torch.sin(angle), torch.cos(angle)], dim=1))

    def forward(self, state, cond, tau):
        e = self.embedding(tau)
        h = self.inp(torch.cat([state, cond], dim=1))
        skips = []
        for i in range(4):
            h = self.enc[i](h, e)
            skips.append(h)
            if i < 3:
                h = self.down[i](h)
        h = self.mid2(self.attn(self.mid1(h, e)), e)
        for i in reversed(range(4)):
            h = self.dec[i](torch.cat([h, skips[i]], dim=1), e)
            if i > 0:
                h = self.up[i - 1](F.interpolate(h, scale_factor=2, mode='nearest'))
        return self.out(h)


def forecaster(name_list):
    """
    Forecast function of forecast_mode 'flow', called by pyfortracc.forecast at
    every lead time. The model is trained or loaded here, once.
    """
    return build_forecaster(name_list)


