"""
Residual flow matching forecast (name_list['forecast_mode'] 'flow').

The model draws the forecast image. Its base is the persistence forecast with the
trends of morph_trend (each system moved by its mean vector and dilated/eroded by
its trends, see persistence and morphology), a frozen advection prior as in the
nowcasting models of 2026 (PG-FMM, PDRF, FreCast); the network learns the residual
of the next frame over that base: the growth, the decay, the deformation and the
new systems that the persistence cannot draw. The residual is generated by
conditional flow matching in the space of the image (FlowCast, ICLR 2026;
PixelFlowCast, 2026), with the network predicting the residual itself (data-space
x-prediction, as in PDRF and PixelFlowCast) and a few Euler steps (STEPS); MEMBERS
samples from different noises are combined by their probability matched mean.

The field is the one the tracking sees: the pixels of the clusters (array_x,
array_y, array_values of the tracking table), as the excess over the first
threshold (signed by the operator, so colder is more for the '<' operators),
normalized, and OUTSIDE where there is no system. The network reads (CHANNELS):
    - the base (persistence + trends) of the next frame;
    - the last CONTEXT frames of the tracking;
    - maps of the history of the systems (MAPS): each pixel of a cluster gets the
      values of the step of its cluster (the innermost threshold), computed from
      the tracking table as in the recurrent modes (rnn_model.step_table):
      lifetime, size, intensity, area and intensity trends, mean vector, status
      NEW/MRG/SPL, border, threshold level and the columns of name_list['rnn_aux'];
    - the optical flow field of the tracking (column opt_field, with
      name_list['opt_correction']) spread over the pixels of the clusters, or the
      mean vector of the cluster where there is none.
The output layer starts at zero, so a model without training (or one that learned
nothing) forecasts the persistence with the trends of the window. The image then
enters the tracking cycle again (features extraction, spatial operations, linking),
and the next lead time reads the forecast frame as one more frame of the history; the
trends of the base fade with the lead time (morphology.DAMPING), as in morph_trend.

The training is self-supervised on the tracking table: every frame is a forecast
start, its base is computed with the persistence functions and the target is the
next frame. The network is trained on CROP x CROP crops around the systems, so it is
independent of the size of the grid. As the forecast reads its own frames at the next
lead times, part of the samples are learned at the end of a rollout of ROLLOUT frames
(the pushforward trick): the model generates the first frames without gradient and
learns the last one from them, so that it learns to correct its own errors instead of
compounding them. The settings below are fixed on purpose; the
architecture is set by name_list['rnn_arch'] (base, lr, weight_decay, device). As the
recurrent modes, the model is trained on the whole tracking up to forecast_time, or
on name_list['rnn_train_period'] = [start, end], and saved in
output_path/forecast/models/ (see model_name), where the next calls with the same
settings reuse it; or it is loaded from name_list['rnn_weights'] (inference only).
train_model() trains it without forecasting. Not available with the '==' and '!='
operators (no ordering of the values).
"""
